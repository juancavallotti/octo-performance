#!/usr/bin/env python3
"""Render a closed-model VU sweep into the shape published benchmarks use.

Usage: vuramp-report.py <run-dir>

The output is deliberately the same table a commercial platform's charts show: throughput and
CPU% against virtual users, with the knee point marked. That is the only form in
which our numbers and theirs can sit on the same axis. Everything else in this lab
is open-model; see COMPARISON.md for why this one is not, and what that costs.
"""

import csv
import json
import os
import re
import statistics
import sys


def load_json(path, default=None):
    try:
        with open(path) as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return default


def parse_resources(path):
    """Differentiate the cumulative CPU counter across the measurement window."""
    rows = []
    try:
        with open(path) as fh:
            for r in csv.DictReader(fh):
                try:
                    rows.append((float(r["elapsed_s"]), float(r["cpu_seconds_total"]),
                                 int(r["rss_bytes"])))
                except (ValueError, KeyError):
                    continue
    except OSError:
        return {}
    if len(rows) < 2:
        return {}

    window = rows[-1][0] - rows[0][0]
    cpu = rows[-1][1] - rows[0][1]
    rss = [r[2] for r in rows]
    return {
        "windowSeconds": round(window, 3),
        "cpuSecondsWindow": round(cpu, 4),
        # Expressed as percent of ONE core, matching how a commercial platform reports it.
        "cpuPct": round(cpu / window * 100, 1) if window > 0 else None,
        "rssBytesPeak": max(rss),
        "rssBytesMean": int(statistics.fmean(rss)),
    }


def n(v, digits=1, suffix=""):
    return "n/a" if v is None else f"{v:,.{digits}f}{suffix}"


def mib(v):
    return "n/a" if v is None else f"{v / 1048576:.1f} MiB"


def main():
    run_dir = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
    env = load_json(os.path.join(run_dir, "env.json"), {})

    levels = []
    for name in os.listdir(run_dir):
        m = re.fullmatch(r"vus-(\d+)", name)
        if not m:
            continue
        cell = os.path.join(run_dir, name)
        summary = load_json(os.path.join(cell, "summary.json"))
        if not summary:
            continue
        met = summary.get("metrics", {})
        reqs = (met.get("http_reqs") or {}).get("count", 0)
        res = parse_resources(os.path.join(cell, "resources.csv"))
        cpu_window = res.get("cpuSecondsWindow")
        levels.append({
            "vus": int(m.group(1)),
            "tps": (met.get("http_reqs") or {}).get("rate"),
            "requests": reqs,
            "duration": met.get("http_req_duration") or {},
            "failedRate": (met.get("http_req_failed") or {}).get("rate", 0.0),
            "cpuPct": res.get("cpuPct"),
            "rssPeak": res.get("rssBytesPeak"),
            "cpuMsPerRequest": round(cpu_window * 1000 / reqs, 4)
                               if cpu_window and reqs else None,
        })
    levels.sort(key=lambda x: x["vus"])

    if not levels:
        print("  no VU levels found", file=sys.stderr)
        return 1

    # The knee: the level with the highest sustained throughput. a commercial platform defines it
    # as "the point at which the throughput reaches the maximum value, usually due to
    # the exhaustion of some resource". Levels that failed requests are not eligible
    # — a server shedding load is not at its knee, it is past it.
    healthy = [l for l in levels if (l["failedRate"] or 0) < 0.01 and l["tps"]]
    knee = max(healthy, key=lambda l: l["tps"]) if healthy else None

    hw = env.get("hardware", {})
    container = env.get("container", {})

    a = [].append
    lines = []
    a = lines.append
    a("---")
    a(f'title: "VU sweep — {env.get("scenario", "")}"')
    a("---")
    a("")
    a(f"# Closed-model VU sweep — {env.get('scenario', '')}")
    a("")
    a(f"**Octo {env.get('versionUnderTest', '?')}** · target `{env.get('target', '?')}` · "
      f"host `{env.get('hostProfile', '?')}`")
    a("")
    if container.get("cpuLimit"):
        a(f"Container capped at **{container['cpuLimit']} CPU** "
          f"({container.get('memLimit') or 'memory uncapped'}) to match the envelope "
          f"the comparison numbers were published at.")
        a("")
    a(f"Hardware: {hw.get('cpuModel', '?')}, {hw.get('logicalCores', '?')} logical cores, "
      f"{hw.get('memoryBytes', 0) / 1024**3:.0f} GB.")
    a("")
    a("> **This is the lab's only closed-model test.** Load is generated by a fixed "
      "population of virtual users that each wait for a response before sending the "
      "next request, so throughput is what the clients could *extract*, not what the "
      "server was *asked* for. It exists to produce a curve comparable to published "
      "vendor benchmarks, which are all closed-model. Do not compare these numbers "
      "with the open-model numbers elsewhere in `results/`.")
    a("")

    # ---- the table ----
    a("## Throughput and CPU against virtual users")
    a("")
    a("| VUs | TPS | CPU % of one core | p95 | p99 | CPU-ms/req | Peak RSS | Failed |")
    a("|---|---|---|---|---|---|---|---|")
    for l in levels:
        marker = " ⟵ knee" if knee and l["vus"] == knee["vus"] else ""
        a(f"| {l['vus']}{marker} | {n(l['tps'], 0)} | {n(l['cpuPct'], 0, '%')} | "
          f"{n(l['duration'].get('p95'), 2, ' ms')} | {n(l['duration'].get('p99'), 2, ' ms')} | "
          f"{n(l['cpuMsPerRequest'], 3)} | {mib(l['rssPeak'])} | "
          f"{n((l['failedRate'] or 0) * 100, 2, '%')} |")
    a("")

    if knee:
        a(f"**Knee point: {knee['vus']} virtual users**, {n(knee['tps'], 0)} TPS at "
          f"{n(knee['cpuPct'], 0, '%')} of one core.")
        a("")
        # Where the ceiling comes from decides what to do about it, and the two
        # causes look nothing alike in the data.
        if knee["cpuPct"] is not None and knee["cpuPct"] >= 85:
            a("CPU was saturated at the knee, so this is a **CPU-bound** ceiling: more "
              "cores would raise it.")
        else:
            a("CPU was **not** saturated at the knee. The ceiling is concurrency, not "
              "compute — the flow is blocking and `workers` is the limit. More cores "
              "would not help; more workers would. See the tuning note in the scenario "
              "README.")
        a("")

    a("## Files")
    a("")
    a("| VUs | Summary | Resources |")
    a("|---|---|---|")
    for l in levels:
        d = f"vus-{l['vus']}"
        a(f"| {l['vus']} | [`summary.json`]({d}/summary.json) | "
          f"[`resources.csv`]({d}/resources.csv) |")
    a("")
    a("---")
    a("")
    a("See [COMPARISON.md](../../COMPARISON.md) for the published numbers this shape "
      "is meant to be read against, and what the remaining differences cost.")
    a("")

    with open(os.path.join(run_dir, "REPORT.md"), "w") as fh:
        fh.write("\n".join(lines))

    with open(os.path.join(run_dir, "result.json"), "w") as fh:
        json.dump({
            "runId": os.path.basename(run_dir),
            "scenario": env.get("scenario"),
            "target": env.get("target"),
            "hostProfile": env.get("hostProfile"),
            "octoVersion": env.get("versionUnderTest"),
            "test": "vuramp",
            "loadModel": "closed",
            "cpuLimit": container.get("cpuLimit"),
            "levels": levels,
            "knee": knee,
        }, fh, indent=2)
        fh.write("\n")

    print(f"  report -> {os.path.join(run_dir, 'REPORT.md')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
