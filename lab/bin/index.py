#!/usr/bin/env python3
"""Regenerate results/index.md from every run's result.json.

Usage: index.py <results-dir>

Two views: runs newest-first, and a per-scenario regression view grouped by target
so a change between Octo versions is visible at a glance.
"""

import json
import os
import sys
from collections import defaultdict


def load(path):
    try:
        with open(path) as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return None


def n(v, digits=1, suffix=""):
    return "n/a" if v is None else f"{v:,.{digits}f}{suffix}"


def mib(v):
    return "n/a" if v is None else f"{v / 1048576:.1f} MiB"


def gain(base, tuned):
    """Tuned throughput relative to baseline."""
    if not base or not tuned:
        return "n/a"
    return f"{(tuned - base) / base * 100:+.1f}%"


def main():
    results_dir = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "results")
    os.makedirs(results_dir, exist_ok=True)

    runs = []
    for name in sorted(os.listdir(results_dir), reverse=True):
        p = os.path.join(results_dir, name, "result.json")
        if os.path.isfile(p):
            r = load(p)
            if r:
                r["_dir"] = name
                runs.append(r)

    lines = []
    a = lines.append
    a("---")
    a('title: "Benchmark results"')
    a("---")
    a("")
    a("# Benchmark results")
    a("")
    a("Every run recorded by this lab, newest first. Generated by `lab/bin/index.py` — "
      "do not edit by hand.")
    a("")

    if not runs:
        a("_No runs recorded yet._ Run `task bench SCENARIO=001-template-page` to produce one.")
        a("")
        with open(os.path.join(results_dir, "index.md"), "w") as fh:
            fh.write("\n".join(lines))
        print(f"  index -> {os.path.join(results_dir, 'index.md')}")
        return 0

    # ---- all runs ----
    a("## Runs")
    a("")
    a("| Run | Scenario | Target | Octo | Baseline req/s | Tuned req/s | Gain | "
      "Baseline CPU-ms/req | Tuned CPU-ms/req |")
    a("|---|---|---|---|---|---|---|---|---|")
    for r in runs:
        b, t = r.get("baseline") or {}, r.get("tuned") or {}
        a(f"| [{r['_dir']}]({r['_dir']}/REPORT.md) | {r.get('scenario', '')} | "
          f"{r.get('target', '')} | {r.get('octoVersion', '')} | "
          f"{n(b.get('achievedRps'))} | {n(t.get('achievedRps'))} | "
          f"{gain(b.get('achievedRps'), t.get('achievedRps'))} | "
          f"{n(b.get('cpuMsPerRequest'), 3)} | {n(t.get('cpuMsPerRequest'), 3)} |")
    a("")

    # ---- regression view ----
    a("## Regression view")
    a("")
    a("Same scenario and target across Octo versions. A drop in throughput or a rise in "
      "CPU-ms/request between versions is a regression worth investigating.")
    a("")
    by_key = defaultdict(list)
    for r in runs:
        by_key[(r.get("scenario"), r.get("target"), r.get("hostProfile"))].append(r)

    for (scenario, target, host), group in sorted(by_key.items(), key=lambda kv: str(kv[0])):
        if len(group) < 1:
            continue
        a(f"### {scenario} · {target} · {host}")
        a("")
        a("| Octo | Baseline req/s | Baseline p95 | Baseline CPU-ms/req | "
          "Tuned req/s | Tuned p95 | Tuned CPU-ms/req | Idle RSS | Cold start |")
        a("|---|---|---|---|---|---|---|---|---|")
        for r in sorted(group, key=lambda x: str(x.get("octoVersion"))):
            b, t = r.get("baseline") or {}, r.get("tuned") or {}
            fp = r.get("footprint") or {}
            a(f"| {r.get('octoVersion')} | {n(b.get('achievedRps'))} | "
              f"{n(b.get('p95Ms'), 2, ' ms')} | {n(b.get('cpuMsPerRequest'), 3)} | "
              f"{n(t.get('achievedRps'))} | {n(t.get('p95Ms'), 2, ' ms')} | "
              f"{n(t.get('cpuMsPerRequest'), 3)} | {mib(fp.get('idleRssBytesMean'))} | "
              f"{n(fp.get('coldStartMs'), 0, ' ms')} |")
        a("")

    a("---")
    a("")
    a("Numbers are the median repetition. See [METHODOLOGY.md](../METHODOLOGY.md) for how "
      "they are produced and what they do not mean.")
    a("")

    with open(os.path.join(results_dir, "index.md"), "w") as fh:
        fh.write("\n".join(lines))
    print(f"  index -> {os.path.join(results_dir, 'index.md')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
