#!/usr/bin/env python3
"""Regenerate results/index.md from every run's result.json.

Usage: index.py <results-dir>

Two views: runs newest-first, and a per-scenario regression view grouped by target
so a change between Octo versions is visible at a glance.
"""

import json
import os
import sys
from collections import defaultdict


def load(path):
    try:
        with open(path) as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return None


def n(v, digits=1, suffix=""):
    return "n/a" if v is None else f"{v:,.{digits}f}{suffix}"


def mib(v):
    return "n/a" if v is None else f"{v / 1048576:.1f} MiB"


def gain(base, tuned):
    """Tuned throughput relative to baseline."""
    if not base or not tuned:
        return "n/a"
    return f"{(tuned - base) / base * 100:+.1f}%"


def main():
    results_dir = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "results")
    os.makedirs(results_dir, exist_ok=True)

    runs = []
    skipped = 0
    for name in sorted(os.listdir(results_dir), reverse=True):
        p = os.path.join(results_dir, name, "result.json")
        if not os.path.isfile(p):
            continue
        r = load(p)
        if not r:
            continue
        # Capacity probes are calibration, not publication: they deliberately push
        # past saturation and have no tuned arm, so listing them alongside steady
        # results invites reading a saturated ramp as a throughput number. They
        # stay on disk; they just do not appear here.
        if r.get("test") == "capacity":
            skipped += 1
            continue
        r["_dir"] = name
        runs.append(r)

    lines = []
    a = lines.append
    a("---")
    a('title: "Benchmark results"')
    a("---")
    a("")
    a("# Benchmark results")
    a("")
    a("Every run recorded by this lab, newest first. Generated by `lab/bin/index.py` — "
      "do not edit by hand.")
    a("")

    if not runs:
        a("_No runs recorded yet._ Run `task bench SCENARIO=001-template-page` to produce one.")
        a("")
        with open(os.path.join(results_dir, "index.md"), "w") as fh:
            fh.write("\n".join(lines))
        print(f"  index -> {os.path.join(results_dir, 'index.md')}")
        return 0

    # ---- all runs ----
    a("## Runs")
    a("")
    a("| Run | Scenario | Target | Octo | Baseline req/s | Tuned req/s | Gain | "
      "Baseline CPU-ms/req | Tuned CPU-ms/req |")
    a("|---|---|---|---|---|---|---|---|---|")
    for r in runs:
        b, t = r.get("baseline") or {}, r.get("tuned") or {}
        a(f"| [{r['_dir']}]({r['_dir']}/REPORT.md) | {r.get('scenario', '')} | "
          f"{r.get('target', '')} | {r.get('octoVersion', '')} | "
          f"{n(b.get('achievedRps'))} | {n(t.get('achievedRps'))} | "
          f"{gain(b.get('achievedRps'), t.get('achievedRps'))} | "
          f"{n(b.get('cpuMsPerRequest'), 3)} | {n(t.get('cpuMsPerRequest'), 3)} |")
    a("")

    # ---- regression view ----
    a("## Regression view")
    a("")
    a("Same scenario and target across Octo versions. A drop in throughput or a rise in "
      "CPU-ms/request between versions is a regression worth investigating.")
    a("")
    by_key = defaultdict(list)
    for r in runs:
        by_key[(r.get("scenario"), r.get("target"), r.get("hostProfile"))].append(r)

    for (scenario, target, host), group in sorted(by_key.items(), key=lambda kv: str(kv[0])):
        if len(group) < 1:
            continue
        a(f"### {scenario} · {target} · {host}")
        a("")
        a("| Octo | Baseline req/s | Baseline p95 | Baseline CPU-ms/req | "
          "Tuned req/s | Tuned p95 | Tuned CPU-ms/req | Idle RSS | Cold start |")
        a("|---|---|---|---|---|---|---|---|---|")
        for r in sorted(group, key=lambda x: str(x.get("octoVersion"))):
            b, t = r.get("baseline") or {}, r.get("tuned") or {}
            fp = r.get("footprint") or {}
            a(f"| {r.get('octoVersion')} | {n(b.get('achievedRps'))} | "
              f"{n(b.get('p95Ms'), 2, ' ms')} | {n(b.get('cpuMsPerRequest'), 3)} | "
              f"{n(t.get('achievedRps'))} | {n(t.get('p95Ms'), 2, ' ms')} | "
              f"{n(t.get('cpuMsPerRequest'), 3)} | {mib(fp.get('idleRssBytesMean'))} | "
              f"{n(fp.get('coldStartMs'), 0, ' ms')} |")
        a("")

    # ---- cross-target view ----
    #
    # Deliberately last, and deliberately hedged. Rule 5 says compare within a
    # target; this table exists because "does the published image behave like the
    # binary" is still worth asking, not because the two columns are equivalent.
    a("## Native against container")
    a("")
    a("Latest run per scenario and target, same Octo version. On macOS the container "
      "publishes its port through a Docker Desktop userland proxy inside a VM, so the "
      "latency columns measure that path as much as they measure Octo. **CPU-ms per "
      "request is the column to read here** — it is measured inside the container from "
      "the same cumulative counter, and it does not travel through the proxy.")
    a("")

    latest = {}
    for r in runs:  # already newest-first
        key = (r.get("scenario"), r.get("target"), r.get("octoVersion"))
        latest.setdefault(key, r)

    scenarios = sorted({k[0] for k in latest if k[0]})
    a("| Scenario | Octo | Native req/s | Container req/s | Native CPU-ms/req | "
      "Container CPU-ms/req | Native p95 | Container p95 | Native idle RSS | Container idle RSS |")
    a("|---|---|---|---|---|---|---|---|---|---|")
    for sc in scenarios:
        versions = sorted({k[2] for k in latest if k[0] == sc})
        for v in versions:
            nat = latest.get((sc, "native", v))
            doc = latest.get((sc, "docker", v))
            if not nat and not doc:
                continue

            def arm(run):
                """Whichever arm this scenario publishes as its headline."""
                if not run:
                    return {}, {}
                return (run.get("tuned") or run.get("baseline") or {},
                        run.get("footprint") or {})

            na, nf = arm(nat)
            da, df = arm(doc)
            a(f"| {sc} | {v} | {n(na.get('achievedRps'))} | {n(da.get('achievedRps'))} | "
              f"{n(na.get('cpuMsPerRequest'), 3)} | {n(da.get('cpuMsPerRequest'), 3)} | "
              f"{n(na.get('p95Ms'), 2, ' ms')} | {n(da.get('p95Ms'), 2, ' ms')} | "
              f"{mib(nf.get('idleRssBytesMean'))} | {mib(df.get('idleRssBytesMean'))} |")
    a("")
    a("Throughput columns are the tuned arm where a scenario has one, so a missing "
      "cell means that combination has not been run rather than that it failed.")
    a("")
    a("> **Ignore the container column for scenarios 003 and 005.** Both talk to something "
      "running on the host, so the containerised runtime has to reach it as "
      "`host.docker.internal` — out through the VM's NAT, onto the host, back in through a "
      "published port. For 003, which makes three database round trips per request, that path "
      "dominates the measurement completely. The comparable arrangement is container-to-container "
      "on a shared Docker network, which this harness does not do yet. See "
      "[METHODOLOGY.md](../METHODOLOGY.md).")
    a("")

    a("---")
    a("")
    a("Numbers are the median repetition. See [METHODOLOGY.md](../METHODOLOGY.md) for how "
      "they are produced and what they do not mean.")
    if skipped:
        a("")
        a(f"_{skipped} capacity probe(s) are on disk but not listed: they deliberately push past "
          "saturation to locate the knee, so their throughput is not a result._")
    a("")

    with open(os.path.join(results_dir, "index.md"), "w") as fh:
        fh.write("\n".join(lines))
    print(f"  index -> {os.path.join(results_dir, 'index.md')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
